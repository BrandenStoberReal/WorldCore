export function mergeTextOptions(
  partial?: Partial<z.infer<typeof TextOptionsSchema>>,
): z.infer<typeof TextOptionsSchema> {
  return {
    ...TextOptionsDefaults,
    ...partial,
    sysprompt: { ...TextOptionsDefaults.sysprompt, ...partial?.sysprompt },
    context: { ...TextOptionsDefaults.context, ...partial?.context },
    instruct: { ...TextOptionsDefaults.instruct, ...partial?.instruct },
    reasoning: { ...TextOptionsDefaults.reasoning, ...partial?.reasoning },
  };
}
